"""Bundle -> FireMarshal workload for FireSim interval capture.

Produces the same layout and contract as tools/interval-trace/prepare-spec-tests.py, so
FireMarshal, FireSim and tools/interval-trace/check-compact-capture.py work unchanged:

<dest>/<benchmark>/
  <workload>.json         FireMarshal config (base br-base.json, disk image, /output collected)
  benchmark.json          what the capture checker reads (also copied to /output)
  overlay/
    <benchmark>/          the bundle's run/ directory
    interval-submit       launcher: FireSim interval markers around each invocation
    benchmark.json
    specpack-inputs.list  the bundle's files: anything else in the run directory is an output
    run-interval.sh       runs every invocation through the launcher, collects outputs
"""
import json
import math
from pathlib import Path
import re
import shlex
import shutil
import subprocess

from .. import bundle
from ..settings import ROOT

LAUNCHER = ROOT / 'launchers' / 'interval-submit.c'
SIMULATION_OUTPUTS = ['uartlog', 'intervaltrace-0-blocks.csv', 'intervaltrace-0-intervals.jsonl', 'intervaltrace-0.json']
MARKERS = {'start': '00008013', 'end': '00010013'}
REDIRECTIONS = ('>', '>>', '<', '2>', '2>>')
GIB = 1 << 30


def workload_name(kit, size, benchmark):
    return f'{kit.name}-{kit.label}-{size}-{benchmark.replace(".", "-")}'


def build_launcher(settings, out_dir):
    """Compile interval-submit with the bundle's cross toolchain (speckle's flags)."""
    out = out_dir / 'interval-submit'
    subprocess.run([settings.gcc_prefix + 'gcc', '-O3', '-static', '-DRISCV', '-Wall', '-Wextra', '-Werror',
                    '-o', str(out), str(LAUNCHER)], check=True)
    return out


def marker_pcs(settings, launcher):
    text = subprocess.run([settings.gcc_prefix + 'objdump', '-d', str(launcher)], check=True,
                          capture_output=True, text=True).stdout
    pcs = {kind: [int(pc, 16) for pc in re.findall(rf'^\s*([0-9a-f]+):\s+{word}\s', text, re.M)]
           for kind, word in MARKERS.items()}
    if not all(pcs.values()):
        raise RuntimeError(f'{launcher}: interval markers not found')
    return pcs


def _local_files(arguments):
    """Relative file names an argument string mentions (redirection targets included)."""
    return {token for token in shlex.split(arguments)
            if token not in REDIRECTIONS and not token.startswith(('/', '-')) and '..' not in Path(token).parts
            and not re.fullmatch(r'[0-9.eE+-]+', token)}


def _host_command(entry, manifest, bundle_dir, settings):
    """A comparison as a bash command for the checker: run in /output, SPEC set to the kit."""
    if entry['cwd'] not in ('.', None):
        raise ValueError(f'{manifest["benchmark"]}: comparison runs in {entry["cwd"]}, not the run directory')
    program = entry['program']
    if entry['program_is_bundled']:
        name = Path(program).name
        program = (f'SPECPACK_QEMU={shlex.quote(str(settings.qemu))} {shlex.quote(str(ROOT / "bin" / "rv-exec"))} '
                   f'{shlex.quote(str(bundle_dir / "run" / name))}')
    return f'here=$PWD && cd "$SPEC" && . ./shrc > /dev/null && cd "$here" && {program} {entry["arguments_shell"]}'


def _run_script(manifest, named):
    """named: files the output checks mention, copied back even if they are inputs."""
    benchmark = manifest['benchmark']
    lines = ['#!/bin/sh', '# Generated by specpack from the bundle manifest.']
    lines += [f'export {name}={shlex.quote(value)}' for name, value in sorted(manifest['environment'].items())]
    lines += ['ulimit -s unlimited', 'mkdir -p /output/status', 'cp /benchmark.json /output/benchmark.json',
              f'cd /{shlex.quote(benchmark)} || exit 1', 'overall=0']
    for entry in manifest['invocations']:
        if entry['cwd'] not in ('.', None):
            raise ValueError(f'{benchmark}: invocation {entry["index"]} runs in {entry["cwd"]}, not the run directory')
        i = entry['index']
        lines += [f"echo 'BEGIN spec-interval {benchmark} invocation={i}'",
                  f'/interval-submit --status-file /output/status/{i:04d} {entry["program"]} {entry["arguments_shell"]}',
                  'status=$?', 'if [ "$status" -ne 0 ]; then overall=$status; fi',
                  f'echo "END spec-interval {benchmark} invocation={i} status=$status"']
    # Every file the run created, however the benchmark named it (for example llvm's -o targets
    # that its pre-compare script globs), then the inputs the checks read.
    lines += ["find . -type f | sed 's|^\\./||' | grep -vxF -f /specpack-inputs.list > /tmp/specpack-outputs",
              'while read -r f; do mkdir -p "/output/$(dirname "$f")" && cp "$f" "/output/$f"; done < /tmp/specpack-outputs']
    for name in sorted(named):
        lines += [f'if [ -f {shlex.quote(name)} ]; then',
                  f'  mkdir -p {shlex.quote(str(Path("/output") / name).rsplit("/", 1)[0])}',
                  f'  cp {shlex.quote(name)} {shlex.quote("/output/" + name)}', 'fi']
    lines += ['echo "$overall" > /output/exitcode',
              'if [ "$overall" -eq 0 ]; then',
              f"  echo 'PASS spec-interval {benchmark} invocations={len(manifest['invocations'])}'",
              'else', f'  echo "FAIL spec-interval {benchmark} status=$overall"', 'fi', 'exit "$overall"']
    return '\n'.join(lines) + '\n'


def _tree_bytes(path):
    return sum(p.stat().st_size for p in path.rglob('*') if p.is_file())


def package(bundle_dir, dest, settings, kit, launcher, pcs):
    """Write one FireMarshal workload for the bundle at `bundle_dir` into `dest` (replaced)."""
    manifest = json.loads((bundle_dir / 'manifest.json').read_text())
    benchmark, size = manifest['benchmark'], manifest['size']
    if manifest['kit']['name'] != kit.name or manifest['label'] != kit.label:
        raise ValueError(f'{bundle_dir}: bundle is for {manifest["kit"]["name"]}/{manifest["label"]}')

    named = set()
    for section in ('pre_compare', 'compare'):
        for entry in manifest.get(section, []):
            named |= _local_files(entry['arguments_shell'])
    for name in named:
        if name.startswith('/') or '..' in Path(name).parts:
            raise ValueError(f'{benchmark}: unsafe output path {name}')

    work = dest.with_name(dest.name + '.partial')
    if work.exists():
        shutil.rmtree(work)
    overlay = work / 'overlay'
    shutil.copytree(bundle_dir / 'run', overlay / benchmark)
    shutil.copy2(launcher, overlay / 'interval-submit')
    inputs = sorted(set(manifest['files']) | set(manifest['binaries']))
    (overlay / 'specpack-inputs.list').write_text(''.join(f'{name}\n' for name in inputs))
    script = overlay / 'run-interval.sh'
    script.write_text(_run_script(manifest, named))
    script.chmod(0o755)
    subprocess.run(['sh', '-n', str(script)], check=True)

    comparisons = [_host_command(entry, manifest, bundle_dir, settings)
                   for section in ('pre_compare', 'compare') for entry in manifest.get(section, [])]
    metadata = {
        'benchmark': benchmark, 'suite': f'CPU{kit.version}', 'input': size, 'threads': 1,
        'invocations': [dict(epoch=e['index'] + 1, executable=Path(e['program']).name,
                             arguments_shell=e['arguments_shell']) for e in manifest['invocations']],
        'marker_pcs': pcs, 'comparisons': comparisons, 'spec_dir': str(kit.spec_dir),
        'binaries': {name: dict(sha256=d['sha256']) for name, d in manifest['binaries'].items()},
        'launcher_sha256': bundle.sha256(launcher), 'environment': manifest['environment'],
        'bundle': dict(path=str(bundle_dir), manifest_sha256=bundle.sha256(bundle_dir / 'manifest.json'),
                       specpack=manifest['specpack'], validation=manifest['validation']),
    }
    for path in (work / 'benchmark.json', overlay / 'benchmark.json'):
        path.write_text(json.dumps(metadata, indent=2) + '\n')

    rootfs_gib = max(2, math.ceil((2 * _tree_bytes(overlay) + GIB // 2) / GIB))
    name = workload_name(kit, size, benchmark)
    config = dict(name=name, base='br-base.json', workdir=str(dest), overlay=str(dest / 'overlay'),
                  **{'rootfs-size': f'{rootfs_gib}GiB', 'command': './run-interval.sh', 'outputs': ['/output'],
                     'firesim': {'simulation_outputs': SIMULATION_OUTPUTS}})
    (work / f'{name}.json').write_text(json.dumps(config, indent=2) + '\n')
    if dest.exists():
        shutil.rmtree(dest)
    work.rename(dest)
    return dict(benchmark=benchmark, workload=f'{name}.json', config=str(dest / f'{name}.json'),
                invocations=len(manifest['invocations']), rootfs_size=config['rootfs-size'],
                metadata=str(dest / 'benchmark.json'))
